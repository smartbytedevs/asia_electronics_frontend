// All 64 districts, alphabetical — convenient for a <select>.
export const DISTRICTS = Object.freeze(Object.keys(POSTAL_CODES_BY_DISTRICT));

// Postal codes are always four digits in Bangladesh.
const POSTAL_CODE_PATTERN = /^\d{4}$/;

export function isValidPostalCode(value) {
  return POSTAL_CODE_PATTERN.test(String(value ?? "").trim());
}

/**
 * Post offices for a district, each { name, thana, code }.
 * Sorted by thana, then post office, so they group naturally in a select.
 */
export function getPostOffices(district) {
  const rows = POSTAL_CODES_BY_DISTRICT[district];
  if (!rows) {
    return [];
  }
  return rows.map(([name, thana, code]) => ({ name, thana, code }));
}

/**
 * A sensible default office for a district: the GPO when there is one, then
 * the district's own "Sadar" office, then a post office named after the
 * district, then any Sadar office, then the first listed office. Returns null
 * for unknown districts.
 */
export function getDefaultPostOffice(district) {
  const offices = getPostOffices(district);
  if (offices.length === 0) {
    return null;
  }
  const lower = district.toLowerCase();
  return (
    offices.find((office) => /\bGPO\b/i.test(office.name)) ??
    offices.find((office) => office.name.toLowerCase() === `${lower} sadar`) ??
    offices.find((office) => office.name.toLowerCase() === lower) ??
    offices.find((office) => /\bSadar\b/i.test(office.name)) ??
    offices[0]
  );
}

export function getDefaultPostalCode(district) {
  return getDefaultPostOffice(district)?.code ?? "";
}

/** Stable key for a post office option (names can repeat with a different code). */
export function postOfficeKey(office) {
  return office ? `${office.code}|${office.name}` : "";
}
